import { describe, expect, it, vi } from 'vitest';
import { elementOf, has, manualScheduler, moveOnCanvas, setup } from './source-fixture.js';
import {
  createSourceController,
  cursorAnchor,
  cursorIn,
  headerLength,
  RECONCILE_DELAY_MS,
  RECONCILE_MAX_WAIT_MS,
  type SourceControllerOptions,
  type SyncResult,
  sourceOf,
} from './source-sync.js';

const withLabel = (text: string, from: string, to: string) => text.replace(`label: ${from}`, `label: ${to}`);

/** A controller over a fake view: the text it holds, the banner and the replacements it was told to make. */
function controlled() {
  const fixture = setup();
  const timer = manualScheduler();
  const view = { text: sourceOf(fixture.store, fixture.registries, fixture.one), banner: false, replaced: 0, results: [] as (SyncResult | undefined)[] };
  const port: SourceControllerOptions['port'] = {
    text: () => view.text,
    replace: (t) => {
      view.text = t;
      view.replaced++;
    },
    banner: (show) => {
      view.banner = show;
    },
    result: (r) => view.results.push(r),
  };
  const controller = createSourceController({ ...fixture, screen: fixture.one, scheduler: timer.scheduler, initial: view.text, port });
  // the author types: the view's text changes, then the controller is told
  const type = (text: string) => {
    view.text = text;
    controller.edit(text);
  };
  return { ...fixture, timer, view, controller, type, port };
}

/** A canvas change, then the quiet time the controller waits before it looks at it. */
function change(c: { readonly timer: { advance(ms: number): void } } & Parameters<typeof moveOnCanvas>[0], label?: string): void {
  moveOnCanvas(c, label);
  c.timer.advance(RECONCILE_DELAY_MS);
}

describe('source view, canvas to text', () => {
  it('FR-EDT-022: a canvas change regenerates the text of a clean view that is not focused', () => {
    const c = controlled();
    expect(c.controller.state().clean).toBe(true);
    change(c);
    expect(c.view.text).toContain('a: { shape: rect, label: Alpha, pin: { x: 300, y: 200 } }');
    expect(c.view.replaced).toBe(1);
    expect(c.view.banner).toBe(false);
    expect(c.controller.state()).toEqual({ clean: true, canvasChanged: false });
    // a second change regenerates again: the generated text is the new base
    c.store.history.undo();
    c.timer.advance(RECONCILE_DELAY_MS);
    expect(c.view.text).not.toContain('pin:');
    expect(c.view.replaced).toBe(2);
  });

  it('FR-EDT-022: a focused view is never regenerated by itself: the banner shows, and blur then regenerates', () => {
    const c = controlled();
    c.controller.focus();
    const before = c.view.text;
    change(c);
    expect(c.view.text).toBe(before);
    expect(c.view.banner).toBe(true);
    c.controller.blur();
    expect(c.view.text).toContain('pin: { x: 300, y: 200 }');
    expect(c.view.banner).toBe(false);
  });

  it('FR-EDT-022: a view with a waiting text is dirty: the canvas change raises the banner and the text stays', () => {
    const c = controlled();
    const typed = withLabel(c.view.text, 'Alpha', 'Alp');
    c.type(typed);
    expect(c.controller.state().clean).toBe(false);
    change(c, 'Beta');
    expect(c.view.text).toBe(typed);
    expect(c.view.replaced).toBe(0);
    expect(c.view.banner).toBe(true);
  });

  it('FR-EDT-022: a view with unapplied, erroring text is dirty: the canvas change raises the banner, blur keeps both', () => {
    const c = controlled();
    const bad = c.view.text.replace('shape: rect, label: Alpha', 'shape: rectt, label: Alpha');
    c.type(bad);
    c.timer.advance(300);
    expect(c.view.results.at(-1)?.status).toBe('invalid');
    change(c, 'Beta');
    expect(c.view.text).toBe(bad);
    expect(c.view.banner).toBe(true);
    // blur flushes (nothing waits), the text does not compile: it stays with its diagnostics and the banner stays
    c.controller.focus();
    c.controller.blur();
    expect(c.view.text).toBe(bad);
    expect(c.view.banner).toBe(true);
    expect(c.controller.state()).toEqual({ clean: false, canvasChanged: true });
  });

  it("FR-EDT-022: the view's own apply never regenerates the text nor raises the banner", () => {
    const c = controlled();
    const banners: boolean[] = [];
    (c.port as { banner: (show: boolean) => void }).banner = (show) => {
      banners.push(show);
    };
    // valid but not canonical (spacing): a regeneration WOULD rewrite it
    const typed = c.view.text.replace('a: { shape: rect, label: Alpha }', 'a: {shape: rect, label: Omega}');
    expect(typed).not.toBe(sourceOf(c.store, c.registries, c.one));
    c.type(typed);
    c.timer.advance(300);
    // the quiet time of a look at the canvas passes: the own apply must have been left out of it
    c.timer.advance(RECONCILE_DELAY_MS);
    expect(c.view.text).toBe(typed);
    expect(c.view.replaced).toBe(0);
    expect(banners).toEqual([]);
    expect(has(c.store, 'Omega')).toBe(true);
    expect(c.view.results.at(-1)?.status).toBe('applied');
    expect(c.view.replaced).toBe(0);
    expect(c.view.banner).toBe(false);
    expect(c.controller.state()).toEqual({ clean: true, canvasChanged: false });
  });

  it('FR-EDT-022: blur applies the waiting text at once, without the pause', () => {
    const c = controlled();
    c.controller.focus();
    c.type(withLabel(c.view.text, 'Alpha', 'Omega'));
    expect(has(c.store, 'Omega')).toBe(false);
    c.controller.blur();
    expect(has(c.store, 'Omega')).toBe(true);
    expect(c.timer.count()).toBe(0);
    expect(c.controller.state().clean).toBe(true);
  });

  it('FR-EDT-022: blur flushes first, and a canvas change that came meanwhile is then regenerated when the view is clean', () => {
    const c = controlled();
    c.controller.focus();
    c.type(withLabel(c.view.text, 'Alpha', 'Omega'));
    change(c, 'Beta');
    expect(c.view.banner).toBe(true);
    c.controller.blur();
    expect(has(c.store, 'Omega')).toBe(true);
    expect(c.view.banner).toBe(false);
    expect(c.view.text).toBe(sourceOf(c.store, c.registries, c.one));
  });

  it('FR-EDT-022: Reload replaces the text, drops the waiting text and the diagnostics, and clears the banner', () => {
    const c = controlled();
    c.type(c.view.text.replace('shape: rect, label: Alpha', 'shape: rectt, label: Alpha'));
    c.timer.advance(300);
    change(c);
    expect(c.view.banner).toBe(true);
    c.type(`${c.view.text}# more`);
    c.controller.reload();
    expect(c.view.text).toBe(sourceOf(c.store, c.registries, c.one));
    expect(c.view.text).toContain('pin: { x: 300, y: 200 }');
    expect(c.view.banner).toBe(false);
    expect(c.view.results.at(-1)).toBeUndefined();
    expect(c.timer.count()).toBe(0);
    expect(c.controller.state()).toEqual({ clean: true, canvasChanged: false });
  });

  it('FR-EDT-022: a canvas change that leaves the screen as it was does nothing, and a change on another screen is not shown', () => {
    const c = controlled();
    change(c, 'Gamma');
    expect(c.view.replaced).toBe(0);
    expect(c.view.banner).toBe(false);
    c.controller.focus();
    change(c, 'Gamma');
    expect(c.view.banner).toBe(false);
  });

  it('FR-EDT-022: after dispose the controller ignores the store', () => {
    // the change comes first, so the look is already waiting when dispose() cancels it (a change after dispose only shows the store subscription is gone)
    const clean = controlled();
    moveOnCanvas(clean);
    expect(clean.timer.count()).toBe(2);
    clean.controller.dispose();
    expect(clean.timer.count()).toBe(0);
    clean.timer.advance(RECONCILE_MAX_WAIT_MS);
    expect(clean.view.replaced).toBe(0);
    const focused = controlled();
    focused.controller.focus();
    moveOnCanvas(focused);
    focused.controller.dispose();
    focused.timer.advance(RECONCILE_MAX_WAIT_MS);
    expect(focused.view.banner).toBe(false);
    // and a change after dispose is not even heard
    moveOnCanvas(focused, 'Beta');
    expect(focused.timer.count()).toBe(0);
  });

  it('FR-EDT-022: the cursor is found again on the same line below the same slug', () => {
    const c = controlled();
    const text = c.view.text;
    const pos = text.indexOf('label: Beta') + 3;
    const anchor = cursorAnchor(text, pos);
    expect(anchor.key).toBe('b');
    const moved = text.replace('a: { shape: rect, label: Alpha }', 'a: { shape: rect, label: Alpha, pin: { x: 300, y: 200 } }');
    const at = cursorIn(moved, anchor, headerLength(moved));
    expect(moved.slice(at - 3, at + 8)).toBe('label: Beta'.slice(0, 11));
    expect(cursorIn(moved, { key: 'zz', lines: 0, column: 0, pos: 0 }, 12)).toBe(12);
    expect(cursorAnchor('plain', 2).key).toBeUndefined();
  });

  it('FR-EDT-022: a blur toward the banner does not flush the waiting text; leaving the view does, and Reload discards it', () => {
    const c = controlled();
    c.controller.focus();
    c.type(withLabel(c.view.text, 'Alpha', 'Omega'));
    change(c, 'Beta');
    expect(c.view.banner).toBe(true);
    c.controller.blur({ toBanner: true });
    expect(has(c.store, 'Omega')).toBe(false);
    expect(c.view.banner).toBe(true);
    expect(c.timer.count()).toBe(1);
    c.controller.reload();
    expect(has(c.store, 'Omega')).toBe(false);
    expect(c.view.text).toContain('label: Beta, pin:');
    // another try: leaving the whole view flushes
    c.controller.focus();
    c.type(withLabel(c.view.text, 'Alpha', 'Omega'));
    c.controller.blur({ toBanner: true });
    expect(has(c.store, 'Omega')).toBe(false);
    c.controller.blur();
    expect(has(c.store, 'Omega')).toBe(true);
  });

  it('FR-EDT-022: changes spaced less than the quiet time apart are looked at once the longest wait has passed, not never', () => {
    const c = controlled();
    const decompiles = vi.spyOn(c.store, 'toDocument');
    const nudge = (x: number) =>
      c.execute('element.update', { id: elementOf(c.store, 'Alpha'), fields: { placement: 'pinned', transform: { x, y: 5, w: 160, h: 80 } } });
    // 100 changes 40 ms apart (less than the 50 ms quiet time): the first is at 0, so the look is due at the maximum wait
    for (let i = 0; i < 100; i++) {
      nudge(i + 1);
      if (i === 24) expect(decompiles).not.toHaveBeenCalled();
      c.timer.advance(40);
      if (i === 24) expect(decompiles).toHaveBeenCalledTimes(1);
    }
    expect(RECONCILE_MAX_WAIT_MS).toBe(1000);
    // a look every maximum wait while the churn lasts (at 1000, 2000, 3000 and 4000 ms), and nothing left waiting after the last
    expect(decompiles).toHaveBeenCalledTimes(4);
    c.timer.advance(RECONCILE_MAX_WAIT_MS);
    expect(decompiles).toHaveBeenCalledTimes(4);
  });

  it('FR-EDT-022: one burst of changes and then silence is looked at once, the quiet time after the last', () => {
    const c = controlled();
    const decompiles = vi.spyOn(c.store, 'toDocument');
    for (let i = 0; i < 10; i++) {
      c.execute('element.update', { id: elementOf(c.store, 'Alpha'), fields: { placement: 'pinned', transform: { x: i + 1, y: 5, w: 160, h: 80 } } });
      c.timer.advance(40);
    }
    c.timer.advance(RECONCILE_DELAY_MS - 41);
    expect(decompiles).not.toHaveBeenCalled();
    c.timer.advance(1);
    expect(decompiles).toHaveBeenCalledTimes(1);
    c.timer.advance(RECONCILE_MAX_WAIT_MS * 2);
    expect(decompiles).toHaveBeenCalledTimes(1);
    expect(c.timer.count()).toBe(0);
  });

  it('FR-EDT-022: 100 canvas changes before the quiet time pass are looked at once, a banner that is up is looked at too', () => {
    const c = controlled();
    const decompiles = vi.spyOn(c.store, 'toDocument');
    for (let x = 1; x <= 100; x++)
      c.execute('element.update', { id: elementOf(c.store, 'Alpha'), fields: { placement: 'pinned', transform: { x, y: 5, w: 160, h: 80 } } });
    c.timer.advance(RECONCILE_DELAY_MS - 1);
    expect(decompiles).not.toHaveBeenCalled();
    // a change in the quiet time restarts it: a drag that pauses less than the delay between frames is looked at once, after it
    c.execute('element.update', { id: elementOf(c.store, 'Alpha'), fields: { placement: 'pinned', transform: { x: 101, y: 5, w: 160, h: 80 } } });
    c.timer.advance(RECONCILE_DELAY_MS - 1);
    expect(decompiles).not.toHaveBeenCalled();
    c.timer.advance(1);
    expect(decompiles).toHaveBeenCalledTimes(1);
    expect(c.view.text).toContain('pin: { x: 101, y: 5 }');
    // focused: the banner goes up after one look, and a later change is looked at too (it may restore the text: the banner then goes)
    c.controller.focus();
    change(c, 'Beta');
    expect(c.view.banner).toBe(true);
    decompiles.mockClear();
    change(c, 'Gamma');
    expect(decompiles).toHaveBeenCalledTimes(1);
  });

  it('FR-EDT-022: the banner clears when a later canvas change restores the document to the text, focused or dirty, and the text is left alone', () => {
    const focused = controlled();
    focused.controller.focus();
    const before = focused.view.text;
    change(focused);
    expect(focused.view.banner).toBe(true);
    focused.store.history.undo();
    focused.timer.advance(RECONCILE_DELAY_MS);
    expect(focused.view.banner).toBe(false);
    expect(focused.view.text).toBe(before);
    expect(focused.view.replaced).toBe(0);
    expect(focused.controller.state().canvasChanged).toBe(false);
    // dirty: the author's waiting text says what the canvas then comes to say
    const dirty = controlled();
    const typed = withLabel(dirty.view.text, 'Alpha', 'Alp');
    dirty.type(typed);
    change(dirty, 'Beta');
    expect(dirty.view.banner).toBe(true);
    dirty.store.history.undo();
    dirty.timer.advance(RECONCILE_DELAY_MS);
    expect(dirty.view.banner).toBe(true);
    const alpha = elementOf(dirty.store, 'Alpha');
    const semantic = (dirty.store.get(alpha) as unknown as { semantic: object }).semantic;
    const text = { type: 'doc', content: [{ type: 'paragraph', content: [{ type: 'text', text: 'Alp' }] }] };
    dirty.execute('element.update', { id: alpha, fields: { text, semantic: { ...semantic, label: 'Alp' } } });
    dirty.timer.advance(RECONCILE_DELAY_MS);
    expect(dirty.view.banner).toBe(false);
    expect(dirty.view.text).toBe(typed);
    expect(dirty.view.replaced).toBe(0);
  });

  it('FR-EDT-022: text typed on a screen that was deleted on the canvas is dropped with a status, at the pause, at a flush and at a blur', () => {
    const c = controlled();
    const before = c.store.toDocument();
    c.type(withLabel(c.view.text, 'Alpha', 'Omega'));
    expect(c.execute('screen.delete', { id: c.one }).ok).toBe(true);
    const afterDelete = c.store.toDocument();
    c.timer.advance(300);
    expect(c.view.results.at(-1)?.status).toBe('gone');
    expect(c.controller.pending()).toBe(false);
    expect(c.store.toDocument()).toEqual(afterDelete);
    expect(c.store.get(c.one)).toBeUndefined();
    for (const drop of [() => c.controller.flush(), () => c.controller.blur()]) {
      c.type(withLabel(c.view.text, 'Alpha', 'Omega'));
      drop();
      expect(c.store.toDocument()).toEqual(afterDelete);
      expect(c.view.results.at(-1)?.status).toBe('gone');
    }
    expect(has(c.store, 'Omega')).toBe(false);
    // nothing was undoable but the delete itself: undo brings back the screen as it was
    c.store.history.undo();
    expect(c.store.toDocument()).toEqual(before);
  });
});
