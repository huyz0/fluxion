#!/usr/bin/env node
// Non-negotiable 2: never delete or disable a test to make a gate pass.
//   check-tests-kept.mjs --msg <commit-msg-file>     (run from the commit-msg hook)
//   check-tests-kept.mjs --commit <sha>              (CI: that commit against its first parent)
// Compares each changed test file before and after, as the runner sees it (scripts/gates/
// test-titles.mjs: code only, not strings or comments). Fails when the change deletes a test file,
// removes running cases (net over the whole change), swaps a case title out, makes a test stop
// running (skip/todo/skipIf/runIf/fixme/fails, x-prefix, options, runtime skips, skipped suite) or
// focuses one (.only) — unless the message carries `Removes-test: <reason>`. A case that is only
// retitled (same arguments apart from the title) passes with `Renames-test: <old> -> <new>`; a
// Renames-test pair that matches no such retitle is a false claim and fails even with Removes-test.
// Deleting a released fixture counts as removing a test, and a versioned fixture may not be edited
// (contracts.md rule 10). Runs in commit-msg because the trailers only exist once the message is written.
import { readFileSync } from 'node:fs';
import { git } from './lib.mjs';
import { testTitles } from './test-titles.mjs';

// --commit <sha> (CI): use that commit's own message, so an amended or rebased commit cannot drop a
// trailer unnoticed (M0.7 review F1).
const arg = (k) => {
  const j = process.argv.indexOf(`--${k}`);
  return j >= 0 ? process.argv[j + 1] : undefined;
};
const sha = arg('commit');
const range = sha ? [`${sha}^`, sha] : ['--cached'];
const msg = sha ? git(['log', '-1', '--format=%B', sha]).stdout : arg('msg') ? readFileSync(arg('msg'), 'utf8').replace(/^#.*$/gm, '') : '';
// [ \t]* not \s*: an empty trailer followed by another trailer line must not count as a reason
const trailer = /^Removes-test:[ \t]*\S/m.test(msg);

const isTest = (p) =>
  /\.(test|spec)\.[cm]?[jt]sx?$/.test(p) || (/(^|\/)(tests|e2e)\/.*\.[cm]?[jt]sx?$/.test(p) && !/(^|\/)(helpers|support|fixtures|__fixtures__)[/.]/.test(p));
// Released fixtures count as tests (contracts.md rule 10, M2.18): deleting or renaming one away
// needs Removes-test, and a versioned fixture folder (fixtures/v<x.y>/, __fixtures__/v<x.y>/) is
// immutable. fixtures/docs/ is regenerated by scripts/fixtures/gen.mjs, so editing it is allowed.
const isReleasedFixture = (p) => /^fixtures\/docs\/[^/]+\.flux\.json$/.test(p) || isVersionedFixture(p);
const isVersionedFixture = (p) => /(^|\/)(__fixtures__|fixtures)\/v\d+(\.\d+)*\//.test(p);
const before = (p) => git(['show', `${sha ? `${sha}^` : 'HEAD'}:${p}`]);
const after = (p) => git(['show', sha ? `${sha}:${p}` : `:${p}`]);
const titlesOf = (r) => (r.status === 0 ? testTitles(r.stdout) : []);
// cases are it/test declarations; suites (describe, incl. Playwright test.describe) and steps are not
const isCase = (t) => t.kind === 'it' || t.kind === 'test';

const problems = [];
const immutable = [];
const files = [];
for (const line of git(['diff', ...range, '--name-status', '-M', '--no-color'])
  .stdout.split(/\r?\n/)
  .filter(Boolean)) {
  const [code, a, b] = line.split('\t');
  if (code === 'D' && isTest(a)) problems.push(`deletes test file ${a}`);
  if ((code === 'D' || code.startsWith('R')) && isReleasedFixture(a)) problems.push(`deletes released fixture ${a}`);
  // no trailer excuses this one: a released fixture is fixed by a migration, never edited
  if (code === 'M' && isVersionedFixture(a)) immutable.push(`edits released fixture ${a} (released fixtures are immutable: add a migration)`);
  if (code.startsWith('R') && isTest(a) && !isTest(b)) problems.push(`renames test file ${a} to non-test ${b}`);
  const [oldPath, newPath] = code.startsWith('R') ? [a, b] : [a, a];
  if (!isTest(oldPath) && !isTest(newPath)) continue;
  files.push({
    path: newPath,
    old: code === 'A' ? [] : titlesOf(before(oldPath)),
    now: code === 'D' || !isTest(newPath) ? [] : titlesOf(after(newPath)),
  });
}

// running cases, net over the whole change, so a case moved between files is not a removal
const running = (list) => list.filter((t) => isCase(t) && t.runs);
const oldRunning = files.flatMap((f) => running(f.old).map((t) => ({ ...t, path: f.path })));
// titles as a multiset: one surviving copy of a duplicated title must not hide the removal of
// another (M1.29 review F1)
const tally = (list) => list.reduce((m, t) => m.set(t.title, (m.get(t.title) ?? 0) + 1), new Map());
const nowRunning = tally(files.flatMap((f) => running(f.now)));
const net = oldRunning.length - files.reduce((n, f) => n + running(f.now).length, 0);
for (const f of files) {
  const drop = running(f.old).length - running(f.now).length;
  if (net > 0 && drop > 0) problems.push(`${f.path}: removes ${drop} test case(s)`);
  const stopped = f.now.filter((t) => !t.runs).length - f.old.filter((t) => !t.runs).length;
  if (stopped > 0) problems.push(`${f.path}: ${stopped} more test(s) or suite(s) do not run (skip/todo/skipIf/runIf/fixme/fails)`);
  const focused = f.now.filter((t) => t.focused).length - f.old.filter((t) => t.focused).length;
  if (focused > 0) problems.push(`${f.path}: adds ${focused} .only`);
}
// case swap: fewer running copies of a title after the change than before. A title rename is
// declared with `Renames-test: <old> -> <new>` (one per line); each pair must match a swapped-out
// title and an added one, so the trailer cannot excuse a removal (M1.26, M1 cp2 F2).
const oldTally = tally(oldRunning);
const added = new Map([...nowRunning].map(([title, n]) => [title, n - (oldTally.get(title) ?? 0)]).filter(([, n]) => n > 0));
// arguments without the title, per title: a rename keeps them (M1.26 review F2)
const restsOf = (list) => list.reduce((m, t) => m.set(t.title, [...(m.get(t.title) ?? []), t.rest]), new Map());
const oldRests = restsOf(oldRunning);
const nowRests = restsOf(files.flatMap((f) => running(f.now)));
// a title may itself contain ' -> ': keep every split point and use the one that matches (review F1)
const renames = [...msg.matchAll(/^Renames-test:[ \t]*(.+?)[ \t]*\r?$/gm)].map(([, raw]) => ({
  raw,
  splits: [...raw.matchAll(/ -> /g)].map((m) => ({ from: raw.slice(0, m.index), to: raw.slice(m.index + 4) })),
  used: false,
}));
const retitled = (from, to) => (added.get(to) ?? 0) > 0 && (oldRests.get(from) ?? []).some((r) => (nowRests.get(to) ?? []).includes(r));
const renamedAway = (title) => {
  for (const r of renames.filter((x) => !x.used)) {
    const split = r.splits.find((s) => s.from === title && retitled(s.from, s.to));
    if (!split) continue;
    r.used = true;
    added.set(split.to, added.get(split.to) - 1);
    return true;
  }
  return false;
};
const firstPath = new Map(oldRunning.toReversed().map((t) => [t.title, t.path]));
for (const [title, n] of oldTally) {
  let missing = n - (nowRunning.get(title) ?? 0);
  while (missing > 0 && renamedAway(title)) missing--;
  if (missing > 0) problems.push(`${firstPath.get(title)}: case swap — test "${title}" removed and not re-added${n > 1 ? ` (${missing} of ${n} copies)` : ''}`);
}
// a pair that matches nothing is a false statement in the message: always an error
const badRenames = renames
  .filter((r) => !r.used)
  .map((r) => `Renames-test "${r.raw}" does not match a removed test and an added test with the same arguments (only the title may change)`);
if (badRenames.length || immutable.length) {
  for (const b of [...badRenames, ...immutable]) console.error(`tests-kept: ${b}`);
  process.exit(1);
}

if (problems.length && !trailer) {
  for (const p of problems) console.error(`tests-kept: ${p}`);
  console.error('A renamed case: add "Renames-test: <old title> -> <new title>". A real removal: add "Removes-test: <reason>" (reviewed like any change).');
  process.exit(1);
}
if (problems.length) console.log(`tests-kept: ${problems.length} removal(s) justified by Removes-test trailer`);
process.exit(0);
