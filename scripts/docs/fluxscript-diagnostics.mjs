#!/usr/bin/env node
// The "FluxScript diagnostics" reference, generated from the code registry of @fluxion/dsl (`DSL_CODES`, ADR-0030, FR-DSL-006): every
// FluxScript code with its default severity and when the compiler reports it.
//   fluxscript-diagnostics.mjs           write apps/docs/src/content/docs/reference/fluxscript-diagnostics.md
//   fluxscript-diagnostics.mjs --check   fail when the written page is not what the registry generates
// Reads the built dsl (packages/dsl/dist): run after `pnpm run build`.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const PAGE = join(ROOT, 'apps', 'docs', 'src', 'content', 'docs', 'reference', 'fluxscript-diagnostics.md');
const DIST = join(ROOT, 'packages', 'dsl', 'dist', 'index.js');

/** The page's text for `codes` (`{ [code]: { severity, description } }`), in code order. */
export function render(codes) {
  const rows = Object.keys(codes)
    .sort()
    .map((code) => `| \`${code}\` | ${codes[code].severity} | ${codes[code].description.replaceAll('|', '\\|')} |`);
  return `---
title: FluxScript diagnostics
description: Every diagnostic code the FluxScript compiler reports, with its severity, generated from the code registry.
---

<!-- GENERATED by scripts/docs/fluxscript-diagnostics.mjs from DSL_CODES in @fluxion/dsl: do not edit by hand. -->

The compiler reports a problem as one line: its place (\`L<line>:<col>\`), its severity, its code, a message and, when it can, a
fix (\`hint:\`). Codes are stable: new ones are added, none is renamed. The compiler also reports the document schema's codes
(\`FLX_REF_MISSING\`, \`FLX_TOKEN_UNKNOWN\`, \`FLX_SCHEMA_*\`), listed in the diagnostics reference of the file format.

| Code | Severity | When |
|---|---|---|
${rows.join('\n')}
`;
}

/** The page for the built registry. */
export async function generate() {
  if (!existsSync(DIST)) throw new Error(`${DIST} is missing: run pnpm run build first`);
  const { DSL_CODES } = await import(pathToFileURL(DIST).href);
  return render(DSL_CODES);
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const text = await generate();
  if (process.argv.includes('--check')) {
    const have = existsSync(PAGE) ? readFileSync(PAGE, 'utf8').replace(/\r\n/g, '\n') : '';
    if (have !== text) {
      console.error('fluxscript-diagnostics: the page is not what DSL_CODES generates: run node scripts/docs/fluxscript-diagnostics.mjs');
      process.exit(1);
    }
    console.log('fluxscript-diagnostics: the page matches DSL_CODES');
  } else {
    writeFileSync(PAGE, text);
    console.log(`fluxscript-diagnostics: wrote ${PAGE}`);
  }
}
