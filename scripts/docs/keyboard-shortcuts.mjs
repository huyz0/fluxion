#!/usr/bin/env node
// The "Keyboard shortcuts" guide, generated from the editor's default keymap (FR-EDT-012, M7.27): every action
// whose binding holds in edit mode (or everywhere), with its title and chords, grouped as the cheat sheet does.
//   keyboard-shortcuts.mjs           write apps/docs/src/content/docs/guides/keyboard-shortcuts.md
//   keyboard-shortcuts.mjs --check   fail when the written guide is not what the keymap generates
// Reads the built editor (packages/editor/dist): run after `pnpm run build`.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const GUIDE = join(ROOT, 'apps', 'docs', 'src', 'content', 'docs', 'guides', 'keyboard-shortcuts.md');
const DIST = join(ROOT, 'packages', 'editor', 'dist', 'index.js');

/** The guide's text for the editor's default keymap and tools. */
export async function generate() {
  if (!existsSync(DIST)) throw new Error(`${DIST} is missing: run pnpm run build first`);
  const { DEFAULT_KEYMAP, EDITOR_COMMANDS, createToolRegistry, formatChord, groupTitle, keyGroups, registerBuiltinTools, toolBindings } = await import(
    pathToFileURL(DIST).href
  );
  const tools = createToolRegistry();
  registerBuiltinTools(tools);
  // the registry lists [key, tool, source] entries
  const list = tools.list().map(([, tool]) => tool);
  if (list.length === 0 || toolBindings(list).length === 0)
    throw new Error('keyboard-shortcuts: the built-in tools bind no shortcut: the guide would have no Tools section');
  const titleOf = (id) => EDITOR_COMMANDS.find((c) => c.id === id)?.title;
  const toolTitle = (id) => list.find((t) => t.id === id)?.title;
  const groups = keyGroups([...DEFAULT_KEYMAP, ...toolBindings(list)], {});
  const row = (g) => `| ${groupTitle(g, titleOf, toolTitle)} | ${g.keys.map((k) => `\`${formatChord(k)}\``).join(', ')} |`;
  const section = (heading, filter) => {
    const rows = groups.filter(filter).map(row);
    return rows.length === 0 ? '' : `## ${heading}\n\n| Action | Keys |\n|---|---|\n${rows.join('\n')}\n\n`;
  };
  return `---
title: Keyboard shortcuts
description: Every default keyboard shortcut of the editor, generated from its keymap.
---

<!-- GENERATED by scripts/docs/keyboard-shortcuts.mjs from the editor's default keymap: do not edit by hand. -->

Shortcuts use \`Ctrl\` on Windows and Linux and \`Cmd\` on a Mac. Press \`?\` in the editor for the same list,
where each shortcut can be changed; changes are kept in your settings.

${section('Editing', (g) => g.when === 'edit' && g.command !== 'tool.use')}${section('Tools', (g) => g.command === 'tool.use')}${section('Presenting', (g) => g.when !== 'edit' && g.command !== 'tool.use')}`.replace(
    /\n+$/,
    '\n',
  );
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const text = await generate();
  if (process.argv.includes('--check')) {
    const have = existsSync(GUIDE) ? readFileSync(GUIDE, 'utf8').replace(/\r\n/g, '\n') : '';
    if (have !== text) {
      console.error('keyboard-shortcuts: the guide is not what the keymap generates: run node scripts/docs/keyboard-shortcuts.mjs');
      process.exit(1);
    }
    console.log('keyboard-shortcuts: the guide matches the keymap');
  } else {
    writeFileSync(GUIDE, text);
    console.log(`keyboard-shortcuts: wrote ${GUIDE}`);
  }
}
