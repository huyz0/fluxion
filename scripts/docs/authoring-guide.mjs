#!/usr/bin/env node
// The "Authoring guide for AI" reference (FR-AI-011), generated from what a model needs to write FluxScript: the cheat sheet, the catalog of
// the bundled packs, the FluxScript diagnostic codes and a corpus example. starlight-llms-txt then folds the page into llms.txt and llms-full.txt.
//   authoring-guide.mjs           write apps/docs/src/content/docs/reference/authoring-guide.md
//   authoring-guide.mjs --check   fail when the written page is not what the sources generate, or when a guide names an id the catalog lacks
// Reads the built workspaces (their dist): run after `pnpm run build`.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const DOCS = join(ROOT, 'apps', 'docs', 'src', 'content', 'docs');
export const PAGE = join(DOCS, 'reference', 'authoring-guide.md');
const EXAMPLE = join(ROOT, 'examples', 'dsl', 'layered-flow.flux.yaml');
const dist = (dir) => join(ROOT, dir, 'dist', 'index.js');

/** `markdown` with every heading one level deeper (headings inside code fences are left alone). */
export function demote(markdown) {
  let fenced = false;
  return markdown
    .split('\n')
    .map((line) => {
      if (/^\s*```/.test(line)) fenced = !fenced;
      return !fenced && /^#{1,5} /.test(line) ? `#${line}` : line;
    })
    .join('\n');
}

/** The page for the parts: the cheat sheet, the catalog (markdown), the example file names and one example's text. */
export function render({ cheatSheet, catalog, examples, example }) {
  return `---
title: Authoring guide for AI
description: What a model reads to write FluxScript and patches, generated from the cheat sheet, the catalog and the examples.
---

<!-- GENERATED by scripts/docs/authoring-guide.mjs from the cheat sheet, the catalog and examples/dsl: do not edit by hand. -->

This page is what an AI agent needs to author a Fluxion document: the cheat sheet, then the catalog of every shape, layout, theme and
marker it may name, then a complete example. The diagnostic codes the compiler answers with are in
[FluxScript diagnostics](/fluxion/reference/fluxscript-diagnostics/).

${demote(cheatSheet.trim())}

${demote(catalog.trim())}

## Examples

The corpus in \`examples/dsl/\`: ${examples.map((e) => `\`${e}\``).join(', ')}. One in full:

\`\`\`yaml flux
${example.trim()}
\`\`\`
`;
}

/** The ids the catalog lists, from the written page: a `pack:name` in backticks. */
export const catalogIds = (page) => new Set([...page.matchAll(/`([a-z][a-z0-9-]*:[a-z][a-z0-9-]*)`/g)].map((m) => m[1]));

/** The ids and codes the guide pages name that the catalog and the code registry do not have (`pack:name` ids of a catalogued pack, `FLX_` codes). */
export function drift(pages, { ids, packs, codes }) {
  const out = [];
  for (const [name, text] of Object.entries(pages)) {
    for (const m of text.matchAll(/`([a-z][a-z0-9-]*):([a-z][a-z0-9-]*)`/g))
      if (packs.has(m[1]) && !ids.has(`${m[1]}:${m[2]}`)) out.push(`${name}: "${m[1]}:${m[2]}" is not in the catalog`);
    for (const m of text.matchAll(/`(FLX_[A-Z_]+)`/g)) if (!codes.has(m[1])) out.push(`${name}: "${m[1]}" is not a diagnostic code`);
  }
  return [...new Set(out)];
}

async function load(dir) {
  if (!existsSync(dist(dir))) throw new Error(`${dist(dir)} is missing: run pnpm run build first`);
  return import(pathToFileURL(dist(dir)).href);
}

/** The page for the built workspaces. */
export async function generate() {
  const [dsl, schema, sdk, layout, basic, themes] = await Promise.all([
    load('packages/dsl'),
    load('packages/schema'),
    load('packages/sdk'),
    load('packages/layout'),
    load('packs/basic'),
    load('packs/themes-core'),
  ]);
  const registries = sdk.createCoreRegistries();
  for (const pack of [basic.basicPack, themes.themesCorePack]) {
    const done = pack.register(registries);
    if (!done.ok) throw new Error(`pack ${pack.id} failed to register`);
  }
  layout.registerBuiltInLayouts(registries.layouts);
  const built = dsl.buildCatalog(registries, { detail: 'full' });
  const examples = readdirSync(join(ROOT, 'examples', 'dsl'))
    .filter((f) => f.endsWith('.flux.yaml'))
    .sort();
  return {
    text: render({ cheatSheet: dsl.CHEAT_SHEET, catalog: dsl.formatCatalog(built.catalog, 'md'), examples, example: readFileSync(EXAMPLE, 'utf8') }),
    codes: new Set([...Object.keys(dsl.DSL_CODES), ...Object.keys(schema.DIAGNOSTIC_CODES)]),
  };
}

/** The guide pages other than the generated one, by file name. */
export function guidePages() {
  const guides = join(DOCS, 'guides');
  return Object.fromEntries(
    readdirSync(guides)
      .filter((f) => f.endsWith('.md'))
      .map((f) => [`guides/${f}`, readFileSync(join(guides, f), 'utf8')]),
  );
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const { text, codes } = await generate();
  if (process.argv.includes('--check')) {
    const have = existsSync(PAGE) ? readFileSync(PAGE, 'utf8').replace(/\r\n/g, '\n') : '';
    const problems = [];
    if (have !== text) problems.push('the page is not what its sources generate: run node scripts/docs/authoring-guide.mjs');
    const packs = new Set([...catalogIds(text)].map((id) => id.split(':')[0]));
    problems.push(...drift(guidePages(), { ids: catalogIds(text), packs, codes }));
    if (problems.length > 0) {
      console.error(`authoring-guide:\n  ${problems.join('\n  ')}`);
      process.exit(1);
    }
    console.log('authoring-guide: the page is current and the guides name only catalogued ids and real codes');
  } else {
    writeFileSync(PAGE, text);
    console.log(`authoring-guide: wrote ${PAGE}`);
  }
}
